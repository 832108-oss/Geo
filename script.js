// SIMULATION CHALLENGE GAMEPAD ROUTINES
function startMiniGame() {
  const dataset = proHotspotDatabase[currentZoneKey];
  if (!dataset || !dataset.game) return;

  const mapState = document.getElementById("map-view-state");
  const gameState = document.getElementById("game-view-state");
  
  mapState.classList.remove("active");
  gameState.classList.add("active");

  document.getElementById("game-question").innerText = dataset.game.question;
  const optionsBox = document.getElementById("game-options-box");
  optionsBox.innerHTML = ""; 

  const feedbackPane = document.getElementById("game-feedback-pane");
  feedbackPane.classList.add("hide");
  feedbackPane.className = "game-reply hide";

  dataset.game.options.forEach((optionText, index) => {
    const btn = document.createElement("button");
    btn.className = "option-node-btn";
    btn.innerText = optionText;
    btn.onclick = () => evaluateUserAnswer(index, dataset.game.correctIndex, dataset.game.explanation);
    optionsBox.appendChild(btn);
  });
}

function evaluateUserAnswer(selectedIndex, correctIndex, explanation) {
  const optionsBox = document.getElementById("game-options-box");
  const buttons = optionsBox.querySelectorAll(".option-node-btn");
  const feedbackPane = document.getElementById("game-feedback-pane");

  buttons.forEach(btn => btn.removeAttribute("onclick"));

  if (selectedIndex === correctIndex) {
    buttons[selectedIndex].classList.add("correct");
    feedbackPane.innerText = explanation;
    feedbackPane.className = "game-reply reveal-correct";
  } else {
    buttons[selectedIndex].classList.add("wrong");
    buttons[correctIndex].classList.add("correct");
    feedbackPane.innerText = "Not quite. " + explanation;
    feedbackPane.className = "game-reply reveal-wrong";
  }
  feedbackPane.classList.remove("hide");
}

function exitMiniGame() {
  document.getElementById("game-view-state").classList.remove("active");
  document.getElementById("map-view-state").classList.add("active");
}

