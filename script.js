// REAL-TIME HARDWARE-ACCELERATED ACTIVE SLIDER SCRIPTING
function updateSlidingBoxIndicator(activeButtonElement) {
  const slider = document.getElementById("active-pill-slider");
  if (!activeButtonElement || !slider) return;

  const buttonWidth = activeButtonElement.offsetWidth;
  const buttonLeftOffset = activeButtonElement.offsetLeft;

  slider.style.width = `${buttonWidth}px`;
  slider.style.transform = `translateX(${buttonLeftOffset - 5}px)`; 
}

